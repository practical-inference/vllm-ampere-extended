# Generate release materials for vllm-ampere-extended:
#   - docs/ampere/availability.md  — feature availability by release, derived
#     from docs/ampere/features.list (edit the .list, never the .md)
#   - a release-notes draft: config changes this tag, newly validated manifest
#     entries, and user-facing commits grouped by prefix
#
# Runs on git refs only (no worktree needed). Defaults target the repo this
# script lives in (origin remote); pass --repo/--remote when driving it from
# an automation checkout that holds the release tags. The fork's release-cut
# automation (outside this tree) invokes this at tag time and commits the
# regenerated page to main with the release.
#
# usage: gen-release-materials.sh [--repo <path>] [--remote <name>] [--check]
#                                 [--out <dir>] [--head <ref>]
#                                 [<last-tag> <new-tag>]
#   --check   verify the committed availability.md matches computed reality;
#             exit 1 on drift (staleness alarm for the nightly lane)
#   --out     staging dir for generated files (default: ./release-materials)
#   --head    ref to generate from (default: <remote>/main; point at a local
#             branch to generate before the promote lands)
set -uo pipefail

REPO="$(git -C "$(dirname "$0")" rev-parse --show-toplevel 2>/dev/null || echo)"
REMOTE=origin
CHECK=0
OUT=release-materials
HEAD_REF=""
while [ $# -gt 0 ]; do
  case "$1" in
    --repo)   REPO="$2"; shift 2 ;;
    --remote) REMOTE="$2"; shift 2 ;;
    --check)  CHECK=1; shift ;;
    --out)    OUT="$2"; shift 2 ;;
    --head)   HEAD_REF="$2"; shift 2 ;;
    *)        LAST_TAG="$1"; NEW_TAG="$2"; shift 2 ;;
  esac
done

GIT="git -C $REPO"
[ -n "$REPO" ] || die "cannot locate the repo — pass --repo <path>"
FEATURES_LIST="docs/ampere/features.list"
AVAILABILITY_MD="docs/ampere/availability.md"
die() { echo "FAIL: $*" >&2; exit 1; }

$GIT rev-parse --verify -q "refs/remotes/${REMOTE}/main" >/dev/null \
  || die "no $REMOTE/main in $REPO — git fetch $REMOTE first"
HEAD_REF="${HEAD_REF:-$REMOTE/main}"

# Tag order: creatordate, oldest first — "first release carrying X" logic
# depends on it. Only tags whose commit is an ancestor of $REMOTE/main.
ALL_TAGS=$($GIT tag --list --sort=creatordate --merged "$HEAD_REF")
[ -n "$ALL_TAGS" ] || die "no release tags merged into $REMOTE/main"
LATEST_TAG=$(echo "$ALL_TAGS" | tail -1)
LAST_TAG=${LAST_TAG:-}
NEW_TAG=${NEW_TAG:-$LATEST_TAG}
if [ -z "$LAST_TAG" ]; then
  # default: the tag before NEW_TAG in creatordate order
  LAST_TAG=$(echo "$ALL_TAGS" | grep -B1 "^${NEW_TAG}$" | head -1)
  [ -n "$LAST_TAG" ] && [ "$LAST_TAG" != "$NEW_TAG" ] || LAST_TAG=$(echo "$ALL_TAGS" | head -1)
fi
$GIT rev-parse --verify -q "refs/tags/$NEW_TAG" >/dev/null || die "unknown tag: $NEW_TAG"

# first tag (oldest-first) whose commit contains $1; empty when unreleased
first_tag_containing() {
  local c="$1" t
  for t in $ALL_TAGS; do
    if $GIT merge-base --is-ancestor "$c" "$t" 2>/dev/null; then
      echo "$t"; return
    fi
  done
}

# ---------- availability table ----------
gen_availability() {
  # Links render page-relative on GitHub; the page lives at docs/ampere/, so
  # repo-root-relative registry paths need the up-prefix to resolve.
  local rel_prefix="../../"
  echo "<!-- GENERATED by .buildkite/scripts/gen-release-materials.sh — edit $FEATURES_LIST, not this file. -->"
  echo
  echo "# Feature availability by release"
  echo
  echo "What a release tag gives you, per user-facing feature of our delta."
  echo "\"unreleased\" = in source on main, not yet in any release tag."
  echo
  echo "| Feature | What it does | Doc | First release | In $LATEST_TAG |"
  echo "|---|---|---|---|---|"
  local name ref doc summary first status
  while IFS='|' read -r name ref doc summary; do
    name=$(echo "$name" | xargs); ref=$(echo "$ref" | xargs); doc=$(echo "$doc" | xargs)
    summary=$(echo "$summary" | xargs)
    [ -n "$name" ] || continue
    $GIT cat-file -e "$HEAD_REF:$doc" 2>/dev/null || \
      echo "WARN: $name doc path missing from $HEAD_REF: $doc (dead link in the availability table)" >&2
    case "$ref" in
      since:*)
        first="${ref#since:}"
        $GIT merge-base --is-ancestor "$first" "$HEAD_REF" 2>/dev/null \
          || { echo "WARN: $name pins since:$first which is not in $REMOTE/main" >&2; first="?"; }
        ;;
      *)
        first=$(first_tag_containing "$ref")
        [ -n "$first" ] || first="unreleased"
        ;;
    esac
    if [ "$first" = "unreleased" ]; then
      status="unreleased (in source)"
    elif [ "$first" = "$LATEST_TAG" ]; then
      status="**new in $LATEST_TAG**"
    else
      status="yes (since $first)"
    fi
    echo "| $name | $summary | [$doc](${rel_prefix}${doc}) | $first | $status |"
  done < <(grep -vE '^\s*(#|$)' "$FEATURES_LIST_SRC")
}

# features.list source: prefer the committed tree at $HEAD_REF so --check and
# generation see the same registry even before a worktree exists.
FEATURES_LIST_SRC=$(mktemp)
$GIT show "$HEAD_REF:$FEATURES_LIST" >"$FEATURES_LIST_SRC" 2>/dev/null \
  || die "$FEATURES_LIST missing from $REMOTE/main"

AVAIL_CONTENT=$(gen_availability)

# ---------- release-notes draft ----------
gen_notes() {
  echo "# Release notes draft — $NEW_TAG"
  echo
  echo "_Generated by .buildkite/scripts/gen-release-materials.sh; curate before publishing._"
  echo
  echo "## Config changes this tag"
  gen_availability | grep -F "new in $NEW_TAG" | sed 's/^|//; s/|$//' \
    | awk -F'|' '{ gsub(/^ +| +$/, "", $1); gsub(/^ +| +$/, "", $4); printf "- %s — first in %s\n", $1, $4 }' || true
  echo "_Features still unreleased (in source, no tag yet): see docs/ampere/availability.md._"
  echo
  echo "## Newly validated / manifest changes"
  $GIT diff "$LAST_TAG" "$NEW_TAG" -- docker/ampere-manifest.yaml 2>/dev/null \
    | grep -E "^[+-].*(model:|status:)" | sed 's/^[+-]//' | sed 's/^/    /' || echo "    (none)"
  echo
  echo "## Container tags"
  echo "- Release tag: \`$NEW_TAG\` (commit $(${GIT} rev-parse --short "$NEW_TAG^{commit}")) — GHCR image tags follow the publish step (\`$NEW_TAG\`, \`sha-<7>\`, \`latest\` floats)."
  echo
  for section in "New features:feat:" "Performance:perf:" "Fixes:fix:" "Docs:docs:"; do
    title="${section%%:*}"; prefix="${section#*:}"
    echo "## $title"
    $GIT log --no-merges --format='- %s (%h)' "$LAST_TAG..$NEW_TAG" -- vllm/ csrc/ docs/ docker/ recipes/ \
      | grep -E "^- ${prefix}" | sed "s/^${prefix}: //" | head -20 || true
    echo
  done
  echo "## Evidence"
  echo "- Per-run transcripts: the release's \`evidence-$NEW_TAG.tar.gz\` asset (recipes/ at the tag)."
}

# ---------- modes ----------
if [ "$CHECK" = 1 ]; then
  COMMITTED=$($GIT show "$HEAD_REF:$AVAILABILITY_MD" 2>/dev/null) \
    || die "$AVAILABILITY_MD missing from $REMOTE/main — run generation and commit it"
  COMPUTED=$(gen_availability)
  if [ "$COMMITTED" = "$COMPUTED" ]; then
    echo "availability.md up to date with $HEAD_REF"
  else
    echo "FAIL: $AVAILABILITY_MD is stale vs $HEAD_REF (features.list or tags moved)" >&2
    diff <(echo "$COMMITTED") <(echo "$COMPUTED") | head -20 >&2
    exit 1
  fi
else
  mkdir -p "$OUT"
  echo "$AVAIL_CONTENT" > "$OUT/availability.md"
  gen_notes > "$OUT/release-notes-draft-$NEW_TAG.md"
  echo "generated:"
  echo "  $OUT/availability.md                    (regenerated page — commit to main with the release)"
  echo "  $OUT/release-notes-draft-$NEW_TAG.md    (curate, then attach to the release)"
  echo "range: $LAST_TAG..$NEW_TAG (latest tag: $LATEST_TAG)"
fi
rm -f "$FEATURES_LIST_SRC"
